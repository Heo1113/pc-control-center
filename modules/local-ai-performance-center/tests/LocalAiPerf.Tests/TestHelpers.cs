using System.Text.Json;

namespace LocalAiPerf.Tests;

internal static class Fixtures
{
    public static string Path(params string[] parts)
        => System.IO.Path.Combine([AppContext.BaseDirectory, "Fixtures", .. parts]);

    public static JsonDocument Json(params string[] parts) => JsonDocument.Parse(File.ReadAllText(Path(parts)));
}

/// <summary>A temporary directory deleted after the test.</summary>
internal sealed class TempDir : IDisposable
{
    public TempDir()
    {
        Path = System.IO.Path.Combine(System.IO.Path.GetTempPath(), "lapc-tests", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Path);
    }

    public string Path { get; }

    public string File(string name) => System.IO.Path.Combine(Path, name);

    public void Dispose()
    {
        Microsoft.Data.Sqlite.SqliteConnection.ClearAllPools();
        try
        {
            Directory.Delete(Path, recursive: true);
        }
        catch (IOException)
        {
        }
        catch (UnauthorizedAccessException)
        {
        }
    }
}

/// <summary>Manually advanced clock for deterministic tests.</summary>
internal sealed class ManualTime(DateTimeOffset start) : TimeProvider
{
    private DateTimeOffset _now = start;

    public override DateTimeOffset GetUtcNow() => _now;

    public void Advance(TimeSpan by) => _now += by;
}
